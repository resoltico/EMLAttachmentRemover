#[cfg(all(test, unix))]
pub(crate) mod cleanup_tests {
    use super::*;
    use std::os::unix::fs::PermissionsExt;
    pub(crate) fn fixture(root: &Path) -> Campaign {
        let directory = root.canonicalize().unwrap().join("run");
        for name in ["source", "build", "tmp", "executables"] {
            fs::create_dir_all(directory.join(name)).unwrap();
        }
        Campaign {
            root_owner: eml_fs::BoundDirectory::open(&directory).unwrap(),
            build_owner: eml_fs::BoundDirectory::open(&directory.join("build")).unwrap(),
            tmp_owner: eml_fs::BoundDirectory::open(&directory.join("tmp")).unwrap(),
            executable_owner: eml_fs::BoundDirectory::open(&directory.join("executables")).unwrap(),
            source: directory.join("source"),
            directory,
            sha: "owned-fixture".into(),
            tooling_root: root.to_owned(),
        }
    }
    fn failed_process(status: std::process::ExitStatus) -> ProcessResult {
        ProcessResult {
            status,
            timed_out: false,
            cancelled: false,
            unexpected_survivors: 0,
            cleanup_complete: true,
            elapsed: Duration::ZERO,
            cleanup_elapsed: Duration::ZERO,
        }
    }
    #[test]
    fn settled_failed_child_keeps_replay_image_and_evidence_but_removes_compile_storage() {
        let owned = tempfile::tempdir().unwrap();
        let campaign = fixture(owned.path());
        let script = b"#!/bin/sh\nexit 7\n";
        let executable = campaign.directory.join("build/preparation");
        fs::write(&executable, script).unwrap();
        fs::set_permissions(&executable, fs::Permissions::from_mode(0o700)).unwrap();
        fs::write(executable.with_file_name("preparation.debug"), b"debug").unwrap();
        fs::write(campaign.source.join("evidence"), b"source").unwrap();
        fs::write(campaign.directory.join("finding.log"), b"failed").unwrap();
        let retained = campaign.retain_executable(&executable).unwrap();
        fs::write(campaign.directory.join("build/objects"), vec![0; 1234]).unwrap();
        fs::write(campaign.directory.join("tmp/scratch"), b"scratch").unwrap();
        let status = Command::new(&retained.path).status().unwrap();
        assert_eq!(status.code(), Some(7));
        let cleanup = campaign.cleanup_generated(&failed_process(status));
        assert_eq!(cleanup["state"], "complete");
        assert_eq!(
            cleanup["directories"][0]["terminal_usage"]["regular_file_bytes"],
            1234
        );
        assert_eq!(
            cleanup["directories"][1]["terminal_usage"]["regular_file_bytes"],
            7
        );
        assert_eq!(
            cleanup["retained_executables"]["regular_file_bytes"],
            script.len() + 5
        );
        assert!(!campaign.directory.join("build").exists());
        assert!(!campaign.directory.join("tmp").exists());
        assert_eq!(fs::read(&retained.path).unwrap(), script);
        assert_eq!(
            image_file_identity(&retained.path).unwrap(),
            retained.identity
        );
        assert_eq!(
            fs::read(campaign.directory.join("executables/preparation.debug")).unwrap(),
            b"debug"
        );
        assert_eq!(
            fs::read(campaign.source.join("evidence")).unwrap(),
            b"source"
        );
        assert_eq!(
            fs::read(campaign.directory.join("finding.log")).unwrap(),
            b"failed"
        );
    }
    #[test]
    fn retained_image_never_creates_directories_through_a_rebound_parent_link() {
        let owned = tempfile::tempdir().unwrap();
        let campaign = fixture(owned.path());
        let external = owned.path().join("external");
        fs::create_dir(&external).unwrap();
        fs::write(external.join("sentinel"), b"unrelated").unwrap();
        let input = campaign
            .directory
            .join("build/native-target/release/preparation");
        fs::create_dir_all(input.parent().unwrap()).unwrap();
        fs::write(&input, b"image").unwrap();
        std::os::unix::fs::symlink(
            &external,
            campaign.directory.join("executables/native-target"),
        )
        .unwrap();
        assert!(campaign.retain_executable(&input).is_err());
        assert_eq!(fs::read(&input).unwrap(), b"image");
        assert_eq!(fs::read(external.join("sentinel")).unwrap(), b"unrelated");
        assert_eq!(fs::read_dir(external).unwrap().count(), 1);
    }

    #[test]
    fn rebound_root_never_receives_cleanup_or_result_diagnostics() {
        let owned = tempfile::tempdir().unwrap();
        let campaign = fixture(owned.path());
        let original = owned.path().join("original-run");
        fs::rename(&campaign.directory, &original).unwrap();
        fs::create_dir(&campaign.directory).unwrap();
        fs::write(campaign.directory.join("sentinel"), b"unrelated").unwrap();
        let before = fs::metadata(&campaign.directory)
            .unwrap()
            .modified()
            .unwrap();
        let status = Command::new("/bin/sh")
            .args(["-c", "exit 7"])
            .status()
            .unwrap();
        let cleanup = campaign.cleanup_generated(&failed_process(status));
        assert_eq!(cleanup["state"], "retained");
        assert!(cleanup["receipt_write_error"].as_str().is_some());
        assert!(
            campaign
                .report(&serde_json::json!({"qualified":false,"cleanup":cleanup}))
                .is_err()
        );
        assert!(campaign.command("cargo").is_err());
        assert_eq!(
            fs::read(campaign.directory.join("sentinel")).unwrap(),
            b"unrelated"
        );
        assert_eq!(fs::read_dir(&campaign.directory).unwrap().count(), 1);
        assert_eq!(
            fs::metadata(&campaign.directory)
                .unwrap()
                .modified()
                .unwrap(),
            before
        );
        assert!(!campaign.directory.join("cleanup.json").exists());
        assert!(!campaign.directory.join("result.json").exists());
        assert!(original.join("build").exists());
        assert!(original.join("tmp").exists());
    }

    #[test]
    fn rebound_directory_and_unconfirmed_lifetime_preserve_all_generated_storage() {
        for rebound in [true, false] {
            let owned = tempfile::tempdir().unwrap();
            let campaign = fixture(owned.path());
            fs::write(campaign.directory.join("build/original"), b"owned").unwrap();
            let status = Command::new("/bin/sh")
                .args(["-c", "exit 7"])
                .status()
                .unwrap();
            let mut process = failed_process(status);
            if rebound {
                fs::rename(
                    campaign.directory.join("build"),
                    campaign.directory.join("original-build"),
                )
                .unwrap();
                fs::create_dir(campaign.directory.join("build")).unwrap();
                fs::write(campaign.directory.join("build/sentinel"), b"rebound").unwrap();
            } else {
                process.cleanup_complete = false;
                process.unexpected_survivors = 1;
            }
            let cleanup = campaign.cleanup_generated(&process);
            assert_eq!(cleanup["state"], "retained");
            assert!(campaign.directory.join("tmp").exists());
            assert!(campaign.directory.join("build").exists());
            if rebound {
                assert_eq!(
                    fs::read(campaign.directory.join("build/sentinel")).unwrap(),
                    b"rebound"
                );
                assert_eq!(
                    fs::read(campaign.directory.join("original-build/original")).unwrap(),
                    b"owned"
                );
            } else {
                assert_eq!(
                    fs::read(campaign.directory.join("build/original")).unwrap(),
                    b"owned"
                );
            }
        }
    }
}

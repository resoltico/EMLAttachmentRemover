//! Source-isolated owned campaigns and exact process exit/deadline handling.
use crate::{Result, capture, git};
use serde::Serialize;
use std::{
    fs::{self, File},
    io::{Read, Write},
    path::{Path, PathBuf},
    process::Command,
    time::Duration,
};

/// History needed by the operation, independently of the exact checked-out tree.
pub(crate) enum SourceHistory {
    HeadOnly,
    Reachable,
}

pub(crate) struct Campaign {
    pub directory: PathBuf,
    pub source: PathBuf,
    pub sha: String,
    tooling_root: PathBuf,
    root_owner: eml_fs::BoundDirectory,
    build_owner: eml_fs::BoundDirectory,
    tmp_owner: eml_fs::BoundDirectory,
    executable_owner: eml_fs::BoundDirectory,
}

#[derive(Serialize)]
pub(crate) struct RetainedExecutable {
    pub path: PathBuf,
    pub identity: xtask::archive::ByteIdentity,
    debug_companions: Vec<serde_json::Value>,
}
pub(crate) fn image_file_identity(path: &Path) -> Result<xtask::archive::ByteIdentity> {
    use sha2::{Digest, Sha256};
    if !fs::symlink_metadata(path)?.is_file() {
        return Err("Retained image input is not an ordinary file".into());
    }
    let mut options = fs::OpenOptions::new();
    options.read(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        options.custom_flags(
            (rustix::fs::OFlags::NOFOLLOW | rustix::fs::OFlags::NONBLOCK).bits() as i32,
        );
    }
    let mut file = options.open(path)?;
    let before = file.metadata()?;
    if !before.is_file() {
        return Err("Retained image handle is not ordinary".into());
    }
    let mut digest = Sha256::new();
    let mut byte_length = 0usize;
    let mut bytes = [0; 65536];
    loop {
        let count = file.read(&mut bytes)?;
        if count == 0 {
            break;
        }
        byte_length = byte_length
            .checked_add(count)
            .ok_or("Image byte count overflow")?;
        digest.update(&bytes[..count]);
    }
    if before.len() != byte_length as u64 || file.metadata()?.len() != before.len() {
        return Err("Image length changed during identity observation".into());
    }
    Ok(xtask::archive::ByteIdentity {
        byte_length,
        sha256: digest
            .finalize()
            .iter()
            .map(|byte| format!("{byte:02x}"))
            .collect(),
    })
}

fn generated_usage(path: &Path) -> Result<serde_json::Value> {
    let mut pending = vec![path.to_owned()];
    let mut files = 0u64;
    let mut bytes = 0u64;
    let mut directories = 0u64;
    let mut other_entries = 0u64;
    while let Some(path) = pending.pop() {
        let metadata = fs::symlink_metadata(&path)?;
        if metadata.is_file() {
            files = files
                .checked_add(1)
                .ok_or("Generated file count overflow")?;
            bytes = bytes
                .checked_add(metadata.len())
                .ok_or("Generated byte count overflow")?;
        } else if metadata.is_dir() {
            directories = directories
                .checked_add(1)
                .ok_or("Generated directory count overflow")?;
            for entry in fs::read_dir(path)? {
                pending.push(entry?.path());
            }
        } else {
            other_entries = other_entries
                .checked_add(1)
                .ok_or("Generated entry count overflow")?;
        }
    }
    Ok(
        serde_json::json!({"regular_file_bytes":bytes,"regular_files":files,"directories":directories,"other_entries_not_followed":other_entries}),
    )
}

impl Campaign {
    pub(crate) fn create(root: &Path, role: &str, history: SourceHistory) -> Result<Self> {
        require_stock_topology(root)?;
        let dirty = git(root, &["status", "--porcelain=v1", "--untracked-files=all"])?;
        if !dirty.is_empty() {
            return Err("Commit the current workspace before a source-isolated campaign; dirty/new inputs must not be omitted".into());
        }
        let sha = git(root, &["rev-parse", "HEAD"])?;
        let parent = root.join("target").join(role);
        fs::create_dir_all(&parent)?;
        let directory = tempfile::Builder::new()
            .prefix("run-")
            .tempdir_in(&parent)?
            .keep();
        let source = directory.join("source");
        let mut clone = Command::new("git");
        clone.args(["clone", "--no-local", "--quiet"]);
        if matches!(history, SourceHistory::HeadOnly) {
            clone.arg("--depth=1");
        }
        capture(clone.arg(root).arg(&source))?;
        if git(&source, &["rev-parse", "HEAD"])? != sha {
            return Err("Campaign source clone identity differs from admitted HEAD".into());
        }
        // Cargo resolves configuration from the actual CWD and all ancestors,
        // including ignored target/.cargo paths between root and snapshot.
        require_stock_topology(&source)?;
        fs::create_dir(directory.join("tmp"))?;
        fs::create_dir(directory.join("build"))?;
        fs::create_dir(directory.join("executables"))?;
        let root_owner = eml_fs::BoundDirectory::open(&directory)?;
        let build_owner = eml_fs::BoundDirectory::open(&directory.join("build"))?;
        let tmp_owner = eml_fs::BoundDirectory::open(&directory.join("tmp"))?;
        let executable_owner = eml_fs::BoundDirectory::open(&directory.join("executables"))?;
        Ok(Self {
            directory,
            source,
            sha,
            tooling_root: root.to_owned(),
            root_owner,
            build_owner,
            tmp_owner,
            executable_owner,
        })
    }
    pub(crate) fn command(&self, program: impl AsRef<std::ffi::OsStr>) -> Result<Command> {
        self.check_root_address()?;
        require_stock_topology(&self.source)?;
        let mut command = Command::new(program);
        command
            .current_dir(&self.source)
            .env("TMPDIR", self.directory.join("tmp"))
            .env("TMP", self.directory.join("tmp"))
            .env("TEMP", self.directory.join("tmp"));
        command
            .env("CARGO_TARGET_DIR", self.directory.join("build"))
            .env("CARGO_BUILD_BUILD_DIR", self.directory.join("build"));
        Ok(command)
    }
    pub(crate) fn tool_command(&self, name: &str) -> Result<Command> {
        let mut command = self.command(self.tool_path(name)?)?;
        command.arg(name).env("CARGO_HOME", cargo_home()?).env(
            "RUSTUP_TOOLCHAIN",
            crate::tools::compiler(&self.tooling_root)?,
        );
        Ok(command)
    }
    pub(crate) fn tool_path(&self, name: &str) -> Result<PathBuf> {
        crate::tools::path(&self.tooling_root, name)
    }
    /// Preserve the actual image separately from disposable Cargo intermediates.
    pub(crate) fn retain_executable(&self, source: &Path) -> Result<RetainedExecutable> {
        self.check_generated_addresses()?;
        let build = self.directory.join("build");
        let relative = source.strip_prefix(&build)?;
        if relative
            .components()
            .any(|part| !matches!(part, std::path::Component::Normal(_)))
        {
            return Err("Executable is not an ordinary generated path".into());
        }
        for parent in source
            .parent()
            .ok_or("Executable has no parent")?
            .ancestors()
        {
            if !fs::symlink_metadata(parent)?.is_dir() {
                return Err("Generated executable parent is not ordinary".into());
            }
            if parent == build {
                break;
            }
        }
        let name = source.file_name().ok_or("Executable has no basename")?;
        let path = self.directory.join("executables").join(relative);
        let mut parent = self.directory.join("executables");
        for component in relative
            .parent()
            .ok_or("Retained image has no parent")?
            .components()
        {
            parent.push(component.as_os_str());
            match fs::create_dir(&parent) {
                Ok(()) => {}
                Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => {
                    if !fs::symlink_metadata(&parent)?.is_dir() {
                        return Err("Retained executable parent is not ordinary".into());
                    }
                }
                Err(error) => return Err(error.into()),
            }
        }
        let identity = image_file_identity(source)?;
        if fs::symlink_metadata(&path).is_ok() {
            return Err("Retained executable already exists".into());
        }
        fs::rename(source, &path)?;
        if image_file_identity(&path)? != identity {
            return Err("Retained executable identity changed".into());
        }
        let mut debug_companions = Vec::new();
        for suffix in [".dSYM", ".debug"] {
            let mut debug_name = name.to_os_string();
            debug_name.push(suffix);
            let input = source.with_file_name(&debug_name);
            match fs::symlink_metadata(&input) {
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => continue,
                Err(error) => return Err(error.into()),
                Ok(metadata) if !metadata.is_file() && !metadata.is_dir() => {
                    return Err("Debug companion is not ordinary".into());
                }
                Ok(_) => {}
            }
            let destination = path.with_file_name(debug_name);
            if fs::symlink_metadata(&destination).is_ok() {
                return Err("Retained debug companion already exists".into());
            }
            fs::rename(&input, &destination)?;
            let mut pending = vec![destination.clone()];
            let mut files = std::collections::BTreeMap::new();
            while let Some(item) = pending.pop() {
                let metadata = fs::symlink_metadata(&item)?;
                if metadata.is_file() {
                    files.insert(
                        item.strip_prefix(&self.directory)?.to_owned(),
                        image_file_identity(&item)?,
                    );
                } else if metadata.is_dir() {
                    for entry in fs::read_dir(&item)? {
                        pending.push(entry?.path());
                    }
                } else {
                    return Err("Debug companion contains a nonordinary entry".into());
                }
            }
            debug_companions.push(serde_json::json!({"path":destination,"files":files}));
        }
        Ok(RetainedExecutable {
            path,
            identity,
            debug_companions,
        })
    }

    fn check_root_address(&self) -> Result<()> {
        if !fs::symlink_metadata(&self.directory)?.is_dir()
            || eml_fs::BoundDirectory::open(&self.directory)?.identity()
                != self.root_owner.identity()
        {
            return Err("Campaign root address changed; no namespace writes are permitted".into());
        }
        Ok(())
    }

    pub(crate) fn check_generated_addresses(&self) -> Result<()> {
        for (path, held) in [
            (&self.directory, &self.root_owner),
            (&self.directory.join("build"), &self.build_owner),
            (&self.directory.join("tmp"), &self.tmp_owner),
            (&self.directory.join("executables"), &self.executable_owner),
        ] {
            if !fs::symlink_metadata(path)?.is_dir()
                || eml_fs::BoundDirectory::open(path)?.identity() != held.identity()
            {
                return Err("Owned campaign directory address changed; retain all storage".into());
            }
        }
        Ok(())
    }

    /// Remove only this run's generated directories after confirmed settlement.
    /// Failure evidence, exact source and retained executable images stay present.
    pub(crate) fn cleanup_generated(&self, process: &ProcessResult) -> serde_json::Value {
        let mut receipt = serde_json::json!({"state":"retained","failure":null,"directories":[{"name":"build","removed":false,"error":null},{"name":"tmp","removed":false,"error":null}],"receipt_write_error":null,"measurement_scope":"terminal logical regular-file bytes; not peak usage or a hard quota","retained_executables":null});
        let check = || -> Result<()> {
            if !process.cleanup_complete || process.unexpected_survivors != 0 {
                return Err("Process lifetime is unconfirmed; retain all campaign storage".into());
            }
            self.check_generated_addresses()
        };
        match check() {
            Err(error) => receipt["failure"] = error.to_string().into(),
            Ok(()) => {
                receipt["state"] = "complete".into();
                match generated_usage(&self.directory.join("executables")) {
                    Ok(usage) => receipt["retained_executables"] = usage,
                    Err(error) => {
                        receipt["state"] = "failed".into();
                        receipt["failure"] = error.to_string().into();
                    }
                }
                for (index, name) in ["build", "tmp"].into_iter().enumerate() {
                    match generated_usage(&self.directory.join(name)) {
                        Ok(usage) => receipt["directories"][index]["terminal_usage"] = usage,
                        Err(error) => {
                            receipt["state"] = "failed".into();
                            receipt["directories"][index]["error"] = error.to_string().into();
                            continue;
                        }
                    }
                    match fs::remove_dir_all(self.directory.join(name)) {
                        Ok(()) => receipt["directories"][index]["removed"] = true.into(),
                        Err(error) => {
                            receipt["state"] = "failed".into();
                            receipt["directories"][index]["error"] = error.to_string().into();
                        }
                    }
                }
            }
        }
        if let Err(error) = self.check_root_address() {
            receipt["receipt_write_error"] = format!("{error}; cleanup receipt not written").into();
            return receipt;
        }
        let written = (|| -> Result<()> {
            File::options()
                .write(true)
                .create_new(true)
                .open(self.directory.join("cleanup.json"))?
                .write_all(&serde_json::to_vec_pretty(&receipt)?)?;
            Ok(())
        })();
        if let Err(error) = written {
            receipt["state"] = "failed".into();
            receipt["receipt_write_error"] = error.to_string().into();
        }
        receipt
    }

    pub(crate) fn report(&self, value: &impl Serialize) -> Result<()> {
        self.report_to(value, &mut std::io::stdout().lock())
    }

    pub(crate) fn report_to(&self, value: &impl Serialize, output: &mut impl Write) -> Result<()> {
        let bytes = serde_json::to_vec_pretty(value)?;
        if let Err(error) = self.check_root_address() {
            return Err(format!(
                "{error}; report retained only in this error: {}",
                String::from_utf8_lossy(&bytes)
            )
            .into());
        }
        File::options()
            .write(true)
            .create_new(true)
            .open(self.directory.join("result.json"))?
            .write_all(&bytes)?;
        output.write_all(&bytes)?;
        output.write_all(b"\n")?;
        Ok(())
    }
}
pub(crate) fn pin(root: &Path, name: &str) -> Result<String> {
    let table: toml::Value = toml::from_str(&fs::read_to_string(root.join("xtask/tools.toml"))?)?;
    let version = table
        .get("versions")
        .and_then(|value| value.get(name))
        .and_then(toml::Value::as_str)
        .filter(|value| !value.is_empty() && !value.chars().any(char::is_whitespace))
        .ok_or_else(|| format!("Missing or invalid tool pin {name}"))?;
    Ok(version.to_owned())
}
pub(crate) fn tool_version(root: &Path, tool: &str, pin_name: &str) -> Result<String> {
    let expected = pin(root, pin_name)?;
    let actual = String::from_utf8(capture(
        crate::tools::command(root, tool)?.arg("--version"),
    )?)?;
    if actual.trim() != format!("cargo-{tool} {expected}") {
        return Err(format!(
            "Expected cargo-{tool} {expected}; install the exact version declared in xtask/tools.toml"
        )
        .into());
    }
    Ok(expected)
}
